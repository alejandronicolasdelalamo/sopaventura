export function pixelIcon(name: string, color = 'currentColor', cls = 'picon'): SVGSVGElement {
  const rows = ICONS[name] ?? ICONS.star;
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', '0 0 8 8');
  svg.setAttribute('shape-rendering', 'crispEdges');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', cls);
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === '.') return;
    const r = document.createElementNS(NS, 'rect');
    r.setAttribute('x', String(x)); r.setAttribute('y', String(y)); r.setAttribute('width', '1'); r.setAttribute('height', '1');
    r.setAttribute('fill', ch === '#' ? color : ch === 'o' ? 'rgba(58,42,82,.75)' : '#fff8e8');
    svg.append(r);
  }));
  return svg;
}
